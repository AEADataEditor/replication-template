#!/usr/bin/env python3
"""Maintain the "Source on GitHub" seealso block at the bottom of each help page.

Every page under docs/tools/ and docs/automations/ that documents a script
(and docs/automations/96-92-bitbucket-pipelines.md) ends with a generated
``{seealso}`` admonition: a small GitHub logo and a link to the script on GitHub.
The block sits between BEGIN/END ``source-link`` comments.

Usage:
    python3 tools/doc_source_links.py          # write/refresh the blocks
    python3 tools/doc_source_links.py --check  # exit 1 if any page is missing/stale
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GITHUB_BLOB = "https://github.com/AEADataEditor/replication-template/blob/master/"
BEGIN = "<!-- BEGIN source-link: generated by tools/doc_source_links.py, do not edit by hand -->"
END = "<!-- END source-link -->"
BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
PREFIX_RE = re.compile(r"^96-9\d-")
SPECIAL = {"docs/automations/96-92-bitbucket-pipelines.md": ["bitbucket-pipelines.yml"]}


def doc_pages():
    for sub in ("tools", "automations"):
        for path in sorted(glob.glob(os.path.join(ROOT, "docs", sub, "**", "*.md"), recursive=True)):
            if os.path.basename(path) != "index.md":
                yield path


def sources_for(path):
    """Return repo-relative source files documented by this page."""
    rel = os.path.relpath(path, ROOT)
    if rel in SPECIAL:
        return SPECIAL[rel]
    text = open(path, encoding="utf-8").read()
    m = re.match(r"\(help-([^)]+)\)=", text)
    stem = m.group(1) if m else PREFIX_RE.sub("", os.path.splitext(os.path.basename(path))[0])
    folder = "automations" if "/automations/" in rel else "tools"
    found = sorted(glob.glob(os.path.join(ROOT, folder, stem + ".*")))
    return [os.path.relpath(f, ROOT) for f in found]


def make_block(sources, image="/images/github-mark.svg"):
    links = ", ".join(f"[`{s}`]({GITHUB_BLOB}{s})" for s in sources)
    return (
        f"{BEGIN}\n"
        ":::{seealso}\n"
        f"![GitHub]({image}) Source on GitHub: {links}\n"
        ":::\n"
        f"{END}\n"
    )


def updated(text, block):
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _: block, text)
    return text.rstrip("\n") + "\n\n" + block


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = []
    for path in doc_pages():
        rel = os.path.relpath(path, ROOT)
        sources = sources_for(path)
        if not sources:
            bad.append(f"{rel}: no source file found")
            continue
        text = open(path, encoding="utf-8").read()
        image = os.path.relpath(os.path.join(ROOT, "docs", "images", "github-mark.svg"), os.path.dirname(path))
        new = updated(text, make_block(sources, image))
        if new != text:
            if args.check:
                bad.append(f"{rel}: source-link block missing or stale")
            else:
                open(path, "w", encoding="utf-8").write(new)
    for b in bad:
        print(b, file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
